    fun url(fast: Boolean, lang: String) =
        if (fast) "https://github.com/tesseract-ocr/tessdata_fast/raw/$FAST_COMMIT/$lang.traineddata"
        else "https://github.com/tesseract-ocr/tessdata_best/raw/$BEST_COMMIT/$lang.traineddata"

    /** Git blob id of a file: SHA-1 over "blob <size>\\0" followed by the bytes. */
    fun gitBlobId(f: java.io.File): String {
        val md = java.security.MessageDigest.getInstance("SHA-1")
        md.update("blob ${f.length()}\u0000".toByteArray(Charsets.ISO_8859_1))
        f.inputStream().use { input -> val buf = ByteArray(64 * 1024); while (true) { val n = input.read(buf); if (n < 0) break; md.update(buf, 0, n) } }
        return md.digest().joinToString("") { b -> String.format(java.util.Locale.ROOT, "%02x", b) }
    }

